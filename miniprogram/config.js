// 校外服务的两种形态。2026-09-20 加的，起因是服务类目：
//
//   'catalog' 黄页 —— 只展示店铺和商品信息，买家看中了复制店长微信自己联系。
//                     没有购物车、没有订单、没有配送，平台不撮合交易，
//                     可以挂在现有的「工具」类目下。
//
//   'order'   订单 —— 完整下单流程（购物车、订单、配送、状态机）。
//                     这个形态按微信的类目定义属于「电商平台」（「为多个
//                     经营者提供交易场所」），而该类目在通过后强制要求绑定
//                     微信支付商户号并接入订单发货管理。
//                     所以在真的接入微信支付之前，别用这个值提审。
//
// 有没有支付不是分界线——「为多个经营者提供商品展示 + 下单」这个结构本身
// 就是交易撮合，货到付款的电商也是电商。分界线在有没有下单闭环。
//
// ⚠️ 云函数 buyerOrders 里有一份同名常量，那边才是真正的闸门（前端拦得住
//    手滑，拦不住改包）。改这里的时候必须同步改那里，并重新部署。
