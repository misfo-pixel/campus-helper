//
// 原来那套是重工作流——店长把配送「外包」给队伍，买家按队伍的方案下单，
// 队伍按「批次 × 店长」领活、打取货清单，最后跑三态对账把配送费结清。
// 一共一千六百多行，服务的是一个目前并不存在的角色。
//
// 现在只剩：店长在工作台点「找人配送」→ 选一支队 → 队长收到推送 →
